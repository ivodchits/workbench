import { describe, expect, it } from "vitest";

import { detectChecklist, generatedChecklist, planContext } from "./autopilot";
import { firstOpenStep, generatedPlanText, isGenerated, stepNote, stepSection, tickStep } from "./generatedPlan";

const AT = new Date(2026, 10, 8, 9, 30).getTime();

const plan = (source: "user" | "session" = "user") =>
  generatedPlanText({
    title: "Dark mode",
    session: "workbench",
    source,
    at: AT,
    steps: [
      { title: "Add the theme tokens", details: "Colors in `theme.css`.\n# not a heading", doneWhen: "both themes\nbuild" },
      { title: "Wire the toggle", details: "In the settings panel." },
      { title: "## Document it" },
    ],
  });

describe("generated plans", () => {
  it("are written in the plan format the autopilot reads, marked as Duck's", () => {
    const text = plan();
    expect(text).toBe(
      [
        "# Dark mode",
        "",
        '> Generated by Duck on 2026-11-08 for the autopilot on "workbench", from the steps the user described. It isn\'t part of the project: it lives in Duck\'s data folder, and Duck ticks the Progress list as each step is reviewed done.',
        "",
        "## Progress",
        "",
        "- [ ] Step 1: Add the theme tokens",
        "- [ ] Step 2: Wire the toggle",
        "- [ ] Step 3: Document it",
        "",
        "## Step 1: Add the theme tokens",
        "",
        "Colors in `theme.css`.",
        "\\# not a heading",
        "",
        "Done when: both themes build",
        "",
        "## Step 2: Wire the toggle",
        "",
        "In the settings panel.",
        "",
        "## Step 3: Document it",
        "",
      ].join("\n"),
    );
    expect(isGenerated(text)).toBe(true);
    expect(isGenerated("# A plan\n\nWritten by hand.")).toBe(false);
    expect(plan("session")).toContain("from what the session was working on");
    // The review finds its records and its steps as in any plan.
    const c = planContext(text, ["Step 2"]);
    expect(c).toContain("Progress records:\n## Progress\n\n- [ ] Step 1: Add the theme tokens");
    expect(c).toContain("Step Step 2:\n## Step 2: Wire the toggle\n\nIn the settings panel.");
    // Duck does the ticking, so it isn't on the session's checklist.
    expect(detectChecklist(text)).toContain("the step is ticked in the plan's progress tracker");
    expect(generatedChecklist(text)).toEqual([
      'the step\'s work is done as the plan describes it, and its "Done when" is met where it can be checked from here',
      "the tests were run and reported passing (or the step has nothing to test)",
    ]);
  });

  it("refuses no steps or too many", () => {
    expect(() => generatedPlanText({ title: "x", session: "s", source: "user", at: AT, steps: [] })).toThrow("at least one step");
    const many = Array.from({ length: 31 }, (_, i) => ({ title: `s${i}` }));
    expect(() => generatedPlanText({ title: "x", session: "s", source: "user", at: AT, steps: many })).toThrow("at most 30");
  });

  it("ticks a step by the id the review gives, once", () => {
    let text = plan();
    expect(firstOpenStep(text)).toBe("Step 1");
    text = tickStep(text, "step 1");
    expect(text).toContain("- [x] Step 1: Add the theme tokens");
    expect(tickStep(text, "Step 1")).toBe(text);
    expect(tickStep(text, null)).toBe(text);
    expect(tickStep(text, "the toggle")).toBe(text);
    expect(tickStep(text, "Step 9")).toBe(text);
    expect(firstOpenStep(text)).toBe("Step 2");
    text = tickStep(tickStep(text, "2"), "S3");
    expect(firstOpenStep(text)).toBeNull();
  });

  it("gives the step to send on, or the first open one when the review names none", () => {
    const text = tickStep(plan(), "Step 1");
    expect(stepSection(text, "Step 2")).toBe("## Step 2: Wire the toggle\n\nIn the settings panel.");
    expect(stepSection(text, "Step 10")).toBeNull();
    expect(stepNote(text, "Step 2", "C:\\data\\duck-plans\\w.md")).toBe(
      "This run's plan (written by Duck for it; not in the project) is C:\\data\\duck-plans\\w.md. The step to work on now:\n\n## Step 2: Wire the toggle\n\nIn the settings panel.",
    );
    expect(stepNote(text, null, "p.md")).toContain("## Step 2: Wire the toggle");
    expect(stepNote(tickStep(tickStep(text, "2"), "3"), null, "p.md")).toBe(
      "This run's plan (written by Duck for it; not in the project) is p.md.",
    );
  });
});
