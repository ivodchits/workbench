// Generated autopilot plans: when the user gives the steps in words (or Duck works
// them out from what the session is doing), Duck writes them as a plan file of its
// own and runs the autopilot on it exactly like on a written plan.
//
// - The file is in the format the autopilot reads (`planContext`, `detectChecklist`):
//   a title, a marked "generated" note, a `## Progress` list of checkboxes, and one
//   `## Step N: <title>` section per step, with its details and "Done when".
// - It never goes into the project: it lives in the app's data folder
//   (`<app data>/duck-plans(.dev)/<session id>.md`, `autopilot_plans.rs`), one per
//   session, replaced by the session's next generated plan.
// - The session never saw it, so each prompt the run sends carries the next step's
//   section (`stepNote`), and Duck ticks the Progress list itself as steps are
//   reviewed done (`tickStep`); the session isn't asked to.
// - When the run ends the file stays (the step log and the decisions log name it), so
//   the user can read what was run; the weekly housekeeping removes it once it hasn't
//   changed for a week and no unstopped run uses it.

import { autopilotPlanPrune, autopilotPlanWrite } from "../ipc/assistant";

export interface PlanStep {
  title: string;
  details?: string;
  doneWhen?: string;
}

/** Where the steps came from: the user's words, or Duck's reading of the session. */
export type PlanSource = "user" | "session";

export const MAX_PLAN_STEPS = 30;

/** The first line under a generated plan's title starts with this. */
export const GENERATED_MARK = "> Generated by Duck";

const SOURCE_TEXT: Record<PlanSource, string> = {
  user: "from the steps the user described",
  session: "from what the session was working on (its transcript, commits and todos), confirmed by the user",
};

const oneLine = (s: string) => s.replace(/\s+/g, " ").trim();

/** A step's id in a generated plan. */
export const stepId = (n: number) => `Step ${n}`;

/** The plan file's text. */
export function generatedPlanText(p: {
  title: string;
  steps: PlanStep[];
  source: PlanSource;
  session: string;
  at: number;
}): string {
  if (p.steps.length === 0) throw new Error("A plan needs at least one step.");
  if (p.steps.length > MAX_PLAN_STEPS) throw new Error(`A plan has at most ${MAX_PLAN_STEPS} steps.`);
  const date = new Date(p.at);
  const day = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
  const titles = p.steps.map((s) => oneLine(s.title).replace(/^#+\s*/, "") || "(untitled)");
  const out = [
    `# ${oneLine(p.title) || "Autopilot plan"}`,
    "",
    `${GENERATED_MARK} on ${day} for the autopilot on "${oneLine(p.session)}", ${SOURCE_TEXT[p.source]}. It isn't part of the project: it lives in Duck's data folder, and Duck ticks the Progress list as each step is reviewed done.`,
    "",
    "## Progress",
    "",
    ...titles.map((t, i) => `- [ ] ${stepId(i + 1)}: ${t}`),
  ];
  p.steps.forEach((s, i) => {
    out.push("", `## ${stepId(i + 1)}: ${titles[i]}`);
    // A heading inside the details would end the step's section early.
    const details = s.details?.trim().replace(/^(#{1,6})(\s)/gm, "\\$1$2");
    if (details) out.push("", details);
    if (s.doneWhen?.trim()) out.push("", `Done when: ${oneLine(s.doneWhen)}`);
  });
  return `${out.join("\n")}\n`;
}

export const isGenerated = (text: string) => text.split(/\r?\n/, 4).some((l) => l.startsWith(GENERATED_MARK));

/** The step's number, from an id the review gives ("Step 2", "step 2", "2", "S2"). */
function numberOf(id: string): number | null {
  const m = /^\s*(?:step\s*|s)?(\d+)\b/i.exec(id);
  return m ? Number(m[1]) : null;
}

const heading = (line: string) => /^(#{1,6})\s/.exec(line)?.[1].length ?? 0;

/** `text` with the step's Progress line ticked; the same text when it can't be found
 *  or is ticked already. */
export function tickStep(text: string, id: string | null): string {
  const n = id ? numberOf(id) : null;
  if (n === null) return text;
  const re = new RegExp(`^(\\s*[-*]\\s+)\\[ \\](\\s+Step ${n}:)`, "i");
  const lines = text.split("\n");
  const at = lines.findIndex((l) => re.test(l));
  if (at < 0) return text;
  lines[at] = lines[at].replace(re, "$1[x]$2");
  return lines.join("\n");
}

/** The section of the step `id` ("## Step N: …" to the next heading), or null. */
export function stepSection(text: string, id: string | null): string | null {
  const n = id ? numberOf(id) : null;
  if (n === null) return null;
  const lines = text.split(/\r?\n/);
  const re = new RegExp(`^##\\s+Step ${n}:`, "i");
  const at = lines.findIndex((l) => re.test(l));
  if (at < 0) return null;
  let end = at + 1;
  while (end < lines.length && heading(lines[end]) === 0) end++;
  return lines.slice(at, end).join("\n").trim();
}

/** The first step not ticked yet. */
export function firstOpenStep(text: string): string | null {
  const m = /^\s*[-*]\s+\[ \]\s+(Step \d+):/m.exec(text);
  return m ? m[1] : null;
}

/** What a prompt of the run adds for a generated plan: the step the session goes on
 *  to, since it never read the plan. */
export function stepNote(text: string, next: string | null, path: string): string {
  const section = stepSection(text, next) ?? stepSection(text, firstOpenStep(text));
  const where = `This run's plan (written by Duck for it; not in the project) is ${path}.`;
  return section ? `${where} The step to work on now:\n\n${section}` : where;
}

/** Where generated plans are kept. */
export interface PlanStore {
  /** Write the session's generated plan; its absolute path. */
  write(instanceId: string, text: string): Promise<string>;
  /** Remove the plans unchanged for a week, but those of `keep`; how many went. */
  prune(keep: string[]): Promise<number>;
}

export const ipcPlanStore: PlanStore = {
  write: autopilotPlanWrite,
  prune: autopilotPlanPrune,
};
